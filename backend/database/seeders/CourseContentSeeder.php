    public function run(): void
    {
        $levelId = DB::table('levels')->where('title', '1급')->value('id');

        $topicTitles = [
            'Приветствия', 'Семья и люди', 'Дом и жильё', 'Еда и напитки',
            'Магазины и покупки', 'Транспорт и места', 'Время и погода',
            'Действия и глаголы', 'Качества и состояния', 'Хобби и досуг',
        ];
        foreach ($topicTitles as $i => $title) {
            DB::table('topics')->updateOrInsert(
                ['title' => $title],
                ['title' => $title, 'order' => $i + 1, 'created_at' => now(), 'updated_at' => now()]
            );
        }

        $lessonIds = DB::table('course_items')
            ->where('type', 'lesson')
            ->whereIn('order', self::LESSON_ORDERS)
            ->orderBy('order')
            ->pluck('id', 'order');

        foreach (self::LESSON_ORDERS as $lessonIndex => $order) {
            $lessonId = $lessonIds[$order] ?? null;
            if (!$lessonId) {
                continue;
            }

            $lessonData = $this->lessons[$lessonIndex] ?? null;
            if (!$lessonData) {
                continue;
            }

            $topicId = DB::table('topics')->where('title', $lessonData['topic'])->value('id');

            $wordIds = [];
            foreach ($lessonData['words'] as $i => [$hangul, $translation, $posTitle]) {
                $posId = DB::table('parts_of_speech')->where('title', $posTitle)->value('id');

                DB::table('words')->updateOrInsert(
                    ['hangul' => $hangul],
                    [
                        'hangul' => $hangul,
                        'translation' => $translation,
                        'part_of_speech_id' => $posId,
                        'level_id' => $levelId,
                        'created_at' => now(),
                        'updated_at' => now(),
                    ]
                );
                $wordId = DB::table('words')->where('hangul', $hangul)->value('id');
                $wordIds[$hangul] = $wordId;

                DB::table('lesson_word')->updateOrInsert(
                    ['course_item_id' => $lessonId, 'word_id' => $wordId],
                    ['order' => $i + 1]
                );

                if ($topicId) {
                    DB::table('word_topic')->updateOrInsert(
                        ['word_id' => $wordId, 'topic_id' => $topicId],
                        []
                    );
                }
            }

            foreach ($lessonData['phrases'] as $i => [$hangul, $translation]) {
                DB::table('phrases')->updateOrInsert(
                    ['hangul' => $hangul],
                    [
                        'hangul' => $hangul,
                        'translation' => $translation,
                        'level_id' => $levelId,
                        'created_at' => now(),
                        'updated_at' => now(),
                    ]
                );
                $phraseId = DB::table('phrases')->where('hangul', $hangul)->value('id');

                DB::table('lesson_phrase')->updateOrInsert(
                    ['course_item_id' => $lessonId, 'phrase_id' => $phraseId],
                    ['order' => $i + 1]
                );

                if ($topicId) {
                    DB::table('phrase_topic')->updateOrInsert(
                        ['phrase_id' => $phraseId, 'topic_id' => $topicId],
                        []
                    );
                }

                $this->syncTokens($phraseId, $hangul, $wordIds);
            }
        }

        // Переразбить токены у ВСЕХ фраз (включая созданные DictionarySeeder)
        $allWordIds = DB::table('words')->pluck('id', 'hangul')->toArray();

        $allPhrases = DB::table('phrases')->get(['id', 'hangul']);
        foreach ($allPhrases as $p) {
            $this->syncTokens($p->id, $p->hangul, $allWordIds);
        }
    }

    private function syncTokens(int $phraseId, string $hangul, array $wordIds): void
    {
        $parts = preg_split('/\s+/u', trim($hangul), -1, PREG_SPLIT_NO_EMPTY);

        DB::table('phrase_tokens')->where('phrase_id', $phraseId)->delete();
        DB::table('phrase_word')->where('phrase_id', $phraseId)->delete();

        $lastIndex = count($parts) - 1;
        foreach ($parts as $i => $text) {
            $clean = preg_replace('/[^\p{Hangul}]/u', '', $text);
            $wordId = $this->matchWord($clean, $wordIds);

            DB::table('phrase_tokens')->insert([
                'phrase_id' => $phraseId,
                'order' => $i + 1,
                'text' => $text,
                'space_after' => $i < $lastIndex ? 1 : 0,
                'word_id' => $wordId,
                'grammar_rule_id' => null,
                'created_at' => now(),
                'updated_at' => now(),
            ]);

            if ($wordId) {
                DB::table('phrase_word')->updateOrInsert(
                    ['phrase_id' => $phraseId, 'word_id' => $wordId],
                    []
                );
            }
        }
    }

    private function matchWord(string $token, array $wordIds): ?int
    {
        if ($token === '') {
            return null;
        }

        if (isset($wordIds[$token])) {
            return $wordIds[$token];
        }

        $bestId = null;
        $bestLen = 0;

        foreach ($wordIds as $wordHangul => $id) {
            $stem = $this->stem($wordHangul);
            if ($stem === '') {
                continue;
            }

            if (str_starts_with($token, $stem)) {
                $len = mb_strlen($stem);
                if ($len > $bestLen) {
                    $bestLen = $len;
                    $bestId = $id;
                }
            }
        }

        return $bestId;
    }

    private function stem(string $hangul): string
    {
        if (str_ends_with($hangul, '다') && mb_strlen($hangul) > 1) {
            return mb_substr($hangul, 0, mb_strlen($hangul) - 1);
        }
        return $hangul;
    }
